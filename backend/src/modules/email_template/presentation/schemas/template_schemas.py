def _clean_optional_text(
    value: Any,
) -> Any:
    """
    Trims optional text and converts blank strings to None.
    """
    if isinstance(value, str):
        value = value.strip()
        return value or None

    return value


def _clean_tags(
    value: Any,
) -> list[str]:
    """
    Trims, validates, and removes duplicate template tags.
    """
    if value is None:
        return []

    if not isinstance(value, list):
        raise ValueError(
            "Template tags must be provided as a list"
        )

    cleaned_tags: list[str] = []
    seen_tags: set[str] = set()

    for tag in value:
        if not isinstance(tag, str):
            raise ValueError(
                "Each template tag must be a string"
            )

        cleaned_tag = tag.strip()

        if not cleaned_tag:
            continue

        if len(cleaned_tag) > 50:
            raise ValueError(
                "Each template tag cannot exceed 50 characters"
            )

        normalized_tag = cleaned_tag.casefold()

        if normalized_tag in seen_tags:
            continue

        seen_tags.add(normalized_tag)
        cleaned_tags.append(cleaned_tag)

    if len(cleaned_tags) > 20:
        raise ValueError(
            "A template cannot contain more than 20 tags"
        )

    return cleaned_tags


def _validate_sender_name(
    value: Any,
) -> Any:
    """Validates the optional sender display name."""
    value = _clean_optional_text(value)
    if value is None:
        return None
    if len(value) > 50:
        raise ValueError("From Name cannot exceed 50 characters")
    if not any(character.isalpha() for character in value):
        raise ValueError("From Name must contain at least one letter")
    return value


def _validate_sender_email_length(
    value: Any,
) -> Any:
    """Keeps the short sender-email field within the product limit."""
    value = _clean_optional_text(value)
    if value is not None and len(value) > 50:
        raise ValueError("From Email cannot exceed 50 characters")
    return value


def _validate_body_html(
    value: Any,
) -> Any:
    """
    Prevents an empty template body.

    The original HTML is returned because spacing and formatting may be
    generated by the frontend rich-text editor.
    """
    if not isinstance(value, str) or not value.strip():
        raise ValueError("Email body cannot be empty")

    if len(value) > 200_000:
        raise ValueError("Email body is too large")

    without_script = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", " ", value, flags=re.I | re.S)
    visible_text = re.sub(r"<[^>]+>", " ", without_script)
    visible_text = unescape(visible_text).replace("\xa0", " ").strip()
    has_image = bool(re.search(r"<img\b[^>]*\bsrc\s*=\s*['\"][^'\"]+['\"]", value, flags=re.I))
    if not visible_text and not has_image:
        raise ValueError("Email body cannot be empty")

    return value


class CreateTemplateRequestSchema(BaseSchema):
    """
    Request schema for creating a custom template.

    The frontend rich-text editor generates body_html automatically.
    The user writes and formats the content normally.
    """

    name: NameString = Field(min_length=1, max_length=50)
    subject: str = Field(min_length=1, max_length=255)
    body_html: str = Field(min_length=1, max_length=200_000)

    description: str | None = Field(default=None, max_length=500)
    preheader: str | None = Field(default=None, max_length=255)
    from_name: str | None = Field(default=None, max_length=50)
    from_email: DomainEmail | None = Field(default=None, max_length=50)

    category_id: int | None = Field(default=None, ge=1)

    tags: list[str] = Field(
        default_factory=list,
    )

    is_default: bool = False
    smart_personalization_enabled: bool = False

    @field_validator("name", mode="before")
    @classmethod
    def clean_name(cls, value: Any) -> Any:
        if isinstance(value, str):
            value = value.strip()
        if not value:
            raise ValueError("Template name is required")
        return value

    @field_validator("subject", mode="before")
    @classmethod
    def clean_subject(cls, value: Any) -> Any:
        if isinstance(value, str):
            value = value.strip()
        if not value:
            raise ValueError("Subject line is required")
        return value

    @field_validator(
        "description",
        "preheader",
        "from_name",
        mode="before",
    )
    @classmethod
    def clean_optional_text(
        cls,
        value: Any,
    ) -> Any:
        """
        Trims optional template text fields.
        """
        return _clean_optional_text(value)

    @field_validator(
        "from_name",
        mode="before",
    )
    @classmethod
    def validate_sender_name(
        cls,
        value: Any,
    ) -> Any:
        return _validate_sender_name(value)

    @field_validator(
        "from_email",
        mode="before",
    )
    @classmethod
    def validate_sender_email_length(
        cls,
        value: Any,
    ) -> Any:
        return _validate_sender_email_length(value)

    @field_validator(
        "tags",
        mode="before",
    )
    @classmethod
    def clean_tags(
        cls,
        value: Any,
    ) -> list[str]:
        """
        Cleans and validates template tags.
        """
        return _clean_tags(value)

    @field_validator(
        "body_html",
        mode="before",
    )
    @classmethod
    def validate_body_html(
        cls,
        value: Any,
    ) -> Any:
        """
        Prevents creating a template with an empty body.
        """
        return _validate_body_html(value)


class UpdateTemplateRequestSchema(BaseSchema):
    """
    Request schema for editing a custom template.

    Only fields included in the request are updated.
    """

    name: NameString | None = Field(default=None, max_length=50)
    subject: str | None = Field(default=None, max_length=255)
    body_html: str | None = Field(default=None, max_length=200_000)

