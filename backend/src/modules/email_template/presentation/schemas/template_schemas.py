    preheader: str | None = Field(default=None, max_length=255)
    from_name: str | None = Field(default=None, max_length=50)
    from_email: DomainEmail | None = Field(default=None, max_length=50)

    category_id: int | None = Field(default=None, ge=1)
    tags: list[str] | None = None

    is_default: bool | None = None
    smart_personalization_enabled: bool | None = None

    @field_validator("name", mode="before")
    @classmethod
    def clean_name(cls, value: Any) -> Any:
        if value is None:
            return None
        if isinstance(value, str):
            value = value.strip()
        if not value:
            raise ValueError("Template name is required")
        return value

    @field_validator("subject", mode="before")
    @classmethod
    def clean_subject(cls, value: Any) -> Any:
        if value is None:
            return None
        if isinstance(value, str):
            value = value.strip()
        if not value:
            raise ValueError("Subject line is required")
        return value

    @field_validator(
        "description",
        "preheader",
        "from_name",
        mode="before",
    )
    @classmethod
    def clean_optional_text(
        cls,
        value: Any,
    ) -> Any:
        """
        Trims optional editable fields.

        A blank value clears the field.
        """
        return _clean_optional_text(value)

    @field_validator(
        "from_name",
        mode="before",
    )
    @classmethod
    def validate_sender_name(
        cls,
        value: Any,
    ) -> Any:
        return _validate_sender_name(value)

    @field_validator(
        "from_email",
        mode="before",
    )
    @classmethod
    def validate_sender_email_length(
        cls,
        value: Any,
    ) -> Any:
        return _validate_sender_email_length(value)

    @field_validator(
        "tags",
        mode="before",
    )
    @classmethod
    def clean_tags(
        cls,
        value: Any,
    ) -> list[str] | None:
        """
        Cleans tags when they are provided.

        An empty list or explicit null clears existing tags.
        """
        if value is None:
            return []

        return _clean_tags(value)

    @field_validator(
        "body_html",
        mode="before",
    )
    @classmethod
    def validate_body_html(
        cls,
        value: Any,
    ) -> Any:
        """
        Prevents replacing the body with empty content.
        """
        if value is None:
            return None

        return _validate_body_html(value)


